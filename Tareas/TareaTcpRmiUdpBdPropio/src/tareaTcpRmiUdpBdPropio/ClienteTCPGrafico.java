    private void jBotonBuscarCiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBotonBuscarCiActionPerformed
        String ci = jTextFieldCi.getText().trim();
        if (ci.isEmpty()) {
            jTextoSalida.setText("Ingrese un C.I.");
            return;
        }

        try {
            deudas.clear();
            String mensajeCliente = "buscar_ " + ci;
            toServer.writeUTF(mensajeCliente);
            String mensajeServidor = fromServer.readUTF();

            if (mensajeServidor.contains("-")) {
                String[] partes = mensajeServidor.split("\\.");
                for (String deudaString : partes) {
                    String[] subPartes = deudaString.split("-");
                    String deudaId = subPartes[0];
                    String[] llavesYDatos = subPartes[1].split(",");
                    Map<String, String> detallesDeuda = new HashMap<>();
                    for (String llaveDato : llavesYDatos) {
                        String[] llaveDatoSeparado = llaveDato.split(":");
                        detallesDeuda.put(llaveDatoSeparado[0].trim(), llaveDatoSeparado[1].trim());
                    }
                    deudas.put(deudaId, detallesDeuda);
                }
                updateTable();
                jTextoSalida.setText("Deudas encontradas.");
            } else {
                jTextoSalida.setText("No hay deudas para el C.I. proporcionado.");
                updateTable();
            }
        } catch (IOException e) {
            jTextoSalida.setText("Error al buscar deudas.");
        }
    }//GEN-LAST:event_jBotonBuscarCiActionPerformed

    private void jBotonPagarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBotonPagarActionPerformed
        int selectedRow = jTablaDeudas.getSelectedRow();
        if (selectedRow == -1) {
            jTextoSalida.setText("Seleccione una deuda para pagar.");
            return;
        }

        String deudaId = (String) jTablaDeudas.getValueAt(selectedRow, 0);
        Map<String, String> selectedDeuda = deudas.get(deudaId);
        if (selectedDeuda != null) {
            String result = String.format("ci:%s,anio:%s,impuesto:%s,monto:%s",
                    selectedDeuda.get("ci"),
                    selectedDeuda.get("anio"),
                    selectedDeuda.get("impuesto"),
                    selectedDeuda.get("monto"));

            try {
                String mensajeCliente = "pagar_" + result;
                toServer.writeUTF(mensajeCliente);
                String mensajeServidor = fromServer.readUTF();

                if (mensajeServidor.contains("Deuda pagada exitosamente")) {
                    deudas.remove(deudaId);
                    updateTable();
                    jTextoSalida.setText("Deuda pagada con éxito.");
                } else {
                    jTextoSalida.setText("Error al pagar la deuda. Su C.I. tiene observaciones");
                }
            } catch (IOException e) {
                jTextoSalida.setText("Error al pagar deuda.");
            }
        } else {
            jTextoSalida.setText("Deuda no encontrada.");
        }
    }//GEN-LAST:event_jBotonPagarActionPerformed

