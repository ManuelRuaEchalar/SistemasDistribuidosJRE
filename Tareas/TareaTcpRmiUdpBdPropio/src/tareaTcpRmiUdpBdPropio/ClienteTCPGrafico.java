    private void connectToServer() {
        int port = 5002;
        try {
            client = new Socket("192.168.185.159", port);
            fromServer = new DataInputStream(client.getInputStream());
            toServer = new DataOutputStream(client.getOutputStream());
        } catch (IOException e) {
            jTextoSalida.setText("Error al conectar con el servidor.");
        }
    }
    private void updateTable() {
        DefaultTableModel model = (DefaultTableModel) jTablaDeudas.getModel();
        model.setRowCount(0); // Clear existing rows
        
        for (Map.Entry<String, Map<String, String>> entry : deudas.entrySet()) {
            String deudaId = entry.getKey();
            Map<String, String> detalles = entry.getValue();
            model.addRow(new Object[]{
                deudaId,
                detalles.get("ci"),
                detalles.get("anio"),
                detalles.get("impuesto"),
                detalles.get("monto")
            });
        }
    }

